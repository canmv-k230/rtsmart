const unsigned int k230_pm_dev_desc_count = sizeof(k230_pm_dev_desc) / sizeof(k230_pm_dev_desc[0]);

const struct k230_clk_desc *k230_clk_desc_find(sysctl_clk_node_e node)
{
    unsigned int i;

    for (i = 0; i < k230_clk_desc_count; i++) {
        if (k230_clk_desc[i].node == node)
            return &k230_clk_desc[i];
    }

    return NULL;
}

const struct k230_pm_dev_desc *k230_pm_dev_desc_find(enum k230_pm_dev_id dev)
{
    unsigned int i;

    for (i = 0; i < k230_pm_dev_desc_count; i++) {
        if (k230_pm_dev_desc[i].id == dev)
            return &k230_pm_dev_desc[i];
    }

    return NULL;
}

const char *k230_clk_name(sysctl_clk_node_e node)
{
    const struct k230_clk_desc *desc = k230_clk_desc_find(node);

    return desc ? desc->name : "unknown";
}

const char *k230_pd_name(sysctl_pwr_domain_e pd)
{
    unsigned int i;

    for (i = 0; i < k230_pd_desc_count; i++) {
        if (k230_pd_desc[i].pd == pd)
            return k230_pd_desc[i].name;
    }

    return "unknown";
}

