struct aic8800_rf_command
{
    uint32_t command;
    uint32_t argument_length;
    uint32_t result_length;
    uint32_t reserved;
    uint8_t arguments[AIC8800_RF_ARGUMENT_SIZE];
    uint8_t reserved_padding[2];
    uint8_t result[AIC8800_RF_RESULT_SIZE];
};

#define AIC8800_RF_IOCTL_TYPE 'R'
#define AIC8800_RF_IOCTL_COMMAND \
    AIC8800_RF_IOCTL_ENCODE(AIC8800_RF_IOCTL_READ | AIC8800_RF_IOCTL_WRITE, \
                            AIC8800_RF_IOCTL_TYPE, 0, \
                            sizeof(struct aic8800_rf_command))
#define AIC8800_RF_IOCTL_GET_CHIP_TYPE \
    AIC8800_RF_IOCTL_ENCODE(AIC8800_RF_IOCTL_READ, AIC8800_RF_IOCTL_TYPE, 1, \
                            sizeof(uint32_t))
#define AIC8800_RF_IOCTL_GET_PRODUCT_ID \
    AIC8800_RF_IOCTL_ENCODE(AIC8800_RF_IOCTL_READ, AIC8800_RF_IOCTL_TYPE, 2, \
                            sizeof(uint32_t))

#endif /* __AIC8800_RF_TEST_H__ */
