const char *ehf_country_code_from_rt(rt_country_code_t country)
{
    if ((int)country < 0 || country >= RT_COUNTRY_UNKNOWN ||
        g_country_codes[country][0] == '\0')
    {
        return RT_NULL;
    }
    return g_country_codes[country];
}

rt_country_code_t ehf_country_code_to_rt(const uint8_t *code, size_t length)
{
    int country;
    uint8_t first;
    uint8_t second;

    if (!code || length < 2)
    {
        return RT_COUNTRY_UNKNOWN;
    }
    first = code[0] >= 'a' && code[0] <= 'z' ? code[0] - ('a' - 'A') : code[0];
    second = code[1] >= 'a' && code[1] <= 'z' ? code[1] - ('a' - 'A') : code[1];
    for (country = 0; country < RT_COUNTRY_UNKNOWN; country++)
    {
        if (g_country_codes[country][0] == first &&
            g_country_codes[country][1] == second)
        {
            return (rt_country_code_t)country;
        }
    }
    return RT_COUNTRY_UNKNOWN;
}
