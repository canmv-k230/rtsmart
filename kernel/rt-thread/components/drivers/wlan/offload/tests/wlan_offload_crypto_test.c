/* The SHA-1 PRF derives the PTK for ordinary WPA and WPA2-PSK, so it sits on
 * the most common connection path. Context is
 * min(AA,SPA) || max(AA,SPA) || min(ANonce,SNonce) || max(ANonce,SNonce);
 * 48 bytes is a CCMP PTK and 64 a TKIP PTK. */
static void test_wpa_prf(void)
{
    static const unsigned char pmk[32] = {
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
        0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
        0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
        0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f,
    };
    static const unsigned char context[76] = {
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
        0x88, 0x99, 0xaa, 0xbb, 0x50, 0x51, 0x52, 0x53,
        0x54, 0x55, 0x56, 0x57, 0x58, 0x59, 0x5a, 0x5b,
        0x5c, 0x5d, 0x5e, 0x5f, 0x60, 0x61, 0x62, 0x63,
        0x64, 0x65, 0x66, 0x67, 0x68, 0x69, 0x6a, 0x6b,
        0x6c, 0x6d, 0x6e, 0x6f, 0xa0, 0xa1, 0xa2, 0xa3,
        0xa4, 0xa5, 0xa6, 0xa7, 0xa8, 0xa9, 0xaa, 0xab,
        0xac, 0xad, 0xae, 0xaf, 0xb0, 0xb1, 0xb2, 0xb3,
        0xb4, 0xb5, 0xb6, 0xb7, 0xb8, 0xb9, 0xba, 0xbb,
        0xbc, 0xbd, 0xbe, 0xbf,
    };
    static const unsigned char expected_ccmp[48] = {
        0x00, 0xc8, 0xdd, 0x18, 0x69, 0x30, 0xdb, 0x12,
        0x9d, 0xa4, 0x4f, 0x8b, 0x81, 0x84, 0x9d, 0x2c,
        0xd5, 0x8f, 0x48, 0x8e, 0xd9, 0x43, 0xbe, 0x11,
        0x2d, 0xda, 0x21, 0x45, 0x06, 0xef, 0xe6, 0xf5,
        0xfe, 0xf7, 0xa6, 0xf7, 0x81, 0xb5, 0xf4, 0xdb,
        0x5f, 0x54, 0xaa, 0x2b, 0x5d, 0x35, 0x35, 0x27,
    };
    static const unsigned char expected_tkip[64] = {
        0x00, 0xc8, 0xdd, 0x18, 0x69, 0x30, 0xdb, 0x12,
        0x9d, 0xa4, 0x4f, 0x8b, 0x81, 0x84, 0x9d, 0x2c,
        0xd5, 0x8f, 0x48, 0x8e, 0xd9, 0x43, 0xbe, 0x11,
        0x2d, 0xda, 0x21, 0x45, 0x06, 0xef, 0xe6, 0xf5,
        0xfe, 0xf7, 0xa6, 0xf7, 0x81, 0xb5, 0xf4, 0xdb,
        0x5f, 0x54, 0xaa, 0x2b, 0x5d, 0x35, 0x35, 0x27,
        0xe8, 0xc1, 0xbe, 0x9f, 0xe1, 0x77, 0xfc, 0x32,
        0x69, 0x0f, 0xe2, 0xb3, 0x58, 0x03, 0x9b, 0x65,
    };
    unsigned char output[64];

    memset(output, 0, sizeof(output));
    rt_wlan_offload_wpa_prf(pmk, sizeof(pmk), "Pairwise key expansion",
                            context, sizeof(context), output, 48);
    assert(memcmp(output, expected_ccmp, 48) == 0);
    memset(output, 0, sizeof(output));
    rt_wlan_offload_wpa_prf(pmk, sizeof(pmk), "Pairwise key expansion",
                            context, sizeof(context), output, 64);
    assert(memcmp(output, expected_tkip, 64) == 0);
}

/* Key wrap at GTK size, and the negative path: a failed integrity check must
 * be reported and must not leave key material in the caller's buffer. */
static void test_aes_wrap_key_data(void)
{
    static const unsigned char kek[16] = {
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
        0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
    };
    static const unsigned char plain[32] = {
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
        0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
        0x10, 0x21, 0x32, 0x43, 0x54, 0x65, 0x76, 0x87,
        0x98, 0xa9, 0xba, 0xcb, 0xdc, 0xed, 0xfe, 0x0f,
    };
    static const unsigned char wrapped[40] = {
        0x5f, 0x34, 0x5a, 0x3c, 0x31, 0x53, 0xcc, 0x0c,
        0xb3, 0x70, 0xfd, 0x07, 0xf4, 0xbe, 0x75, 0x0d,
        0x92, 0xb2, 0x61, 0x03, 0x6f, 0x13, 0x5b, 0x50,
        0xe7, 0x27, 0x78, 0xcf, 0xb6, 0xef, 0x5c, 0x36,
        0x8c, 0x9b, 0xc9, 0xe3, 0x1c, 0x2f, 0xb3, 0xf7,
    };
    unsigned char output[40];
    unsigned char damaged[40];
    size_t output_length;
    size_t index;
    size_t leaked = 0;

    output_length = sizeof(output);
    assert(rt_wlan_offload_aes_wrap(kek, plain, sizeof(plain), output,
                                   &output_length) == 0);
    assert(output_length == sizeof(wrapped));
    assert(memcmp(output, wrapped, sizeof(wrapped)) == 0);

    output_length = sizeof(output);
    assert(rt_wlan_offload_aes_unwrap(kek, wrapped, sizeof(wrapped), output,
                                     &output_length) == 0);
    assert(output_length == sizeof(plain));
    assert(memcmp(output, plain, sizeof(plain)) == 0);

    memcpy(damaged, wrapped, sizeof(wrapped));
    damaged[0] ^= 0x01;
    output_length = sizeof(output);
    memset(output, 0xcc, sizeof(output));
    assert(rt_wlan_offload_aes_unwrap(kek, damaged, sizeof(wrapped), output,
                                     &output_length) != 0);
    assert(output_length == 0);
    for (index = 0; index < sizeof(plain); index++)
    {
        leaked += output[index] != 0;
    }
    assert(leaked == 0);
}

